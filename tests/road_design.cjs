const assert=require('node:assert/strict');
const design=require('../wrapper/static/road-design.js');
const points=[{x:0,y:0,height_m:0,snap_enabled:true},{x:400,y:0,height_m:0,snap_enabled:true}];
const source=JSON.stringify(points);
const bridge=design.bridge(points,8);
assert.deepEqual(bridge.map(p=>[p.x,p.y,p.height_m]),[[0,0,0],[100,0,8],[300,0,8],[400,0,0]]);
assert.equal(JSON.stringify(points),source,'Suggestions never mutate input');
assert.equal(bridge[1].snap_enabled,false,'Ramp shoulder is never snapped to a ground node');
assert.equal(bridge[0].snap_enabled,true);
const bent=design.bridge([{x:0,y:0},{x:200,y:0},{x:200,y:200}],8);
assert.deepEqual(bent.map(p=>[p.x,p.y]),[[0,0],[100,0],[200,0],[200,100],[200,200]],'Preserve drawn bends');
assert.throws(()=>design.bridge([{x:0,y:0},{x:100,y:0}],8),/路线太短/);
for(const h of [NaN,Infinity,0,-2,51])assert.throws(()=>design.bridge(points,h));
assert.throws(()=>design.bridge(points.slice(0,1),8));
const raised=design.setHeight(bridge,1,12);
assert.equal(raised[1].height_m,12);
assert.equal(bridge[1].height_m,8);
assert.deepEqual(raised.map(p=>[p.x,p.y]),bridge.map(p=>[p.x,p.y]),'Vertical edit never changes XY');
assert.equal(design.setHeight(bridge,0,18)[0].height_m,0,'Start must stay ground-connected');
assert.equal(design.setHeight(bridge,3,18)[3].height_m,0);
assert.equal(design.setHeight(bridge,1,100)[1].height_m,50);
assert.throws(()=>design.setHeight(bridge,1,NaN));
const p=design.profile(bridge,(x,y)=>x*.01);
assert.equal(p.total,400);assert.equal(p.maxOffsetGrade,.08);
assert.equal(p.handles[1].ground,1);assert.equal(p.handles[1].height,8);
assert.equal(p.samples[10].road,9);
assert.ok(p.samples.every(s=>Number.isFinite(s.road)&&s.road>=s.ground));
assert.equal(design.profile([],()=>0).total,0);
assert.ok(design.profile([{x:0,y:0},{x:1000000,y:0}],()=>0).samples.length<=129,'Long roads keep a bounded profile cost');
const history=design.history();history.remember(points);
assert.deepEqual(history.undo(bridge),points);assert.deepEqual(history.redo(points),bridge);
history.undo(bridge);history.remember(raised);assert.equal(history.canRedo,false);
history.clear();assert.equal(history.canUndo,false);
for(let i=0;i<55;i++)history.remember([{x:i,y:0}]);
let count=0;while(history.canUndo){history.undo([]);count++;}assert.equal(count,50);
console.log('PASS road design: ramps, bends, limits, immutable height edits, locked endpoints, sampled profile, bounded undo/redo.');
