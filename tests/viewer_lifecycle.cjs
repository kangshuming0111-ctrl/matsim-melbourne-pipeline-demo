const assert=require('node:assert/strict');
const {deferred,frameLoop,observeVisibility}=require('../wrapper/static/viewer-lifecycle.js');
(async()=>{
  let scheduled=new Map(),counter=0,draws=[],states=[];
  const loop=frameLoop({request:cb=>{scheduled.set(++counter,cb);return counter;},cancel:id=>scheduled.delete(id),draw:dt=>draws.push(dt),state:s=>states.push(s)});
  const tick=t=>{const [id,cb]=scheduled.entries().next().value;scheduled.delete(id);cb(t);};
  assert.equal(scheduled.size,0);loop.setVisible(true);loop.setVisible(true);
  assert.equal(scheduled.size,1);tick(100);tick(116);assert.deepEqual(draws,[0,.016]);
  loop.setVisible(false);assert.equal(scheduled.size,0);
  loop.setVisible(true);tick(100000);assert.equal(draws.at(-1),0,'resume does not advance hidden simulation time');
  tick(110000);assert.equal(draws.at(-1),.1,'long visible stall is bounded');
  loop.dispose();loop.dispose();loop.setVisible(true);assert.equal(scheduled.size,0);
  assert.equal(states.at(-1),'disposed');
  const idle=frameLoop({request:cb=>{scheduled.set(++counter,cb);return counter;},cancel:id=>scheduled.delete(id),draw:()=>false});
  idle.setVisible(true);tick(1);assert.equal(scheduled.size,0,'static scene has no queued render');
  idle.invalidate();idle.invalidate();assert.equal(scheduled.size,1,'UI changes coalesce into one frame');
  tick(2);assert.equal(scheduled.size,0);idle.setVisible(false);idle.invalidate();assert.equal(scheduled.size,0);idle.dispose();
  let release,loads=0,published=[],freed=[],signal;
  const loader=deferred({load:s=>{loads++;signal=s;return new Promise(r=>release=r);},ready:v=>published.push(v),failed:e=>{throw e;},release:v=>freed.push(v)});
  assert.equal(loads,0);const p=loader.ensure();assert.equal(p,loader.ensure());await Promise.resolve();assert.equal(loads,1);
  loader.dispose();assert.equal(signal.aborted,true);release('old');assert.equal(await p,null);
  assert.deepEqual(published,[]);assert.deepEqual(freed,['old']);assert.equal(await loader.ensure(),null);
  let attempts=0,errors=0;
  const retry=deferred({load:async()=>{if(++attempts===1)throw Error('network');return 'city';},ready:v=>published.push(v),failed:()=>errors++,release:v=>freed.push(v)});
  assert.equal(await retry.ensure(),null);assert.equal(errors,1);assert.equal(await retry.ensure(),'city');
  assert.equal(await retry.ensure(),'city');assert.equal(attempts,2);retry.dispose();retry.dispose();assert.deepEqual(freed,['old','city']);
  const win=new EventTarget(),doc=new EventTarget();win.innerHeight=100;win.innerWidth=100;doc.defaultView=win;doc.hidden=false;
  let rect={width:50,height:50,top:200,bottom:250,left:0,right:50},visibility=[],disconnected=false;
  win.IntersectionObserver=class {observe(){} disconnect(){disconnected=true;}};
  const watcher=observeVisibility({ownerDocument:doc,getBoundingClientRect:()=>rect},v=>visibility.push(v));
  assert.deepEqual(visibility,[false]);rect.top=10;rect.bottom=60;win.dispatchEvent(new Event('scroll'));assert.equal(visibility.at(-1),true);
  doc.hidden=true;doc.dispatchEvent(new Event('visibilitychange'));assert.equal(visibility.at(-1),false);
  doc.hidden=false;doc.dispatchEvent(new Event('visibilitychange'));assert.equal(visibility.at(-1),true);
  rect.width=0;watcher.check();assert.equal(visibility.at(-1),false,'collapsed viewer stays off');
  watcher.dispose();const before=visibility.length;rect.width=50;win.dispatchEvent(new Event('resize'));
  assert.equal(visibility.length,before);assert.equal(disconnected,true);
  console.log('PASS viewer lifecycle: coalescing, cancellation, retry, disposal, visibility, no hidden-time jump');
})().catch(e=>{console.error(e);process.exitCode=1;});
